"""Constants and function signatures of LSL, read once from the bundled builtins.txt.

builtins.txt is generated by update_builtins.py from Linden Lab's lsl-definitions;
the copy in lsltest/data/ is refreshed at the same time. Nothing else in lsltest
declares an LSL constant: EOF, NAK, JSON_* and the rest all come from here, so
they cannot drift from what lslint checks.
"""

import os
import re

from .values import Key, Vector, Rotation, f32, to_int32, unescape

_PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)), "data", "builtins.txt")


def _parse_constant(ctype, raw):
    raw = raw.strip()
    if ctype == "integer":
        return to_int32(int(raw, 0))
    if ctype == "float":
        return f32(float(raw))
    if ctype == "string":
        return unescape(raw[1:-1]) if raw.startswith('"') else raw
    if ctype == "key":
        return Key(raw[1:-1] if raw.startswith('"') else raw)
    if ctype == "vector":
        return Vector(*[float(x) for x in raw.strip("<>").split(",")])
    if ctype in ("rotation", "quaternion"):
        return Rotation(*[float(x) for x in raw.strip("<>").split(",")])
    return raw


def _parse(path):
    constants = {}
    signatures = {}
    with open(path, "r", encoding="utf-8") as handle:
        for line in handle:
            line = line.rstrip("\n")
            if not line or line.startswith("//"):
                continue
            m = re.match(r"const (\w+) (\w+) = (.*)$", line)
            if m:
                ctype, name, raw = m.groups()
                constants[name] = _parse_constant(ctype, raw)
                continue
            if line.startswith("event "):
                continue
            m = re.match(r"(\w+) (\w+)\((.*)\)$", line)
            if m:
                ret, name, params = m.groups()
                types = [p.strip().split()[0] for p in params.split(",") if p.strip()]
                types = ["rotation" if t == "quaternion" else t for t in types]
                signatures[name] = ("rotation" if ret == "quaternion" else ret, types)
    return constants, signatures


CONSTANTS, SIGNATURES = _parse(_PATH)
