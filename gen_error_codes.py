#!/usr/bin/env python3
"""Generate skills/lsl-dev/references/error-codes.md from logger.hh and logger.cc.

Run it after adding a diagnostic. Standard library only.
"""

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent
OUT = ROOT / "skills" / "lsl-dev" / "references" / "error-codes.md"


def enum_names(text, start_name, start_code):
    """Map code -> enum name for the block that starts at start_name."""
    names = {}
    i = text.index(start_name)
    block = text[i:]
    block = block[: block.index("_LAST")]
    code = start_code
    for line in block.splitlines():
        line = line.split("//")[0].strip().rstrip(",")
        if not line:
            continue
        name = line.split("=")[0].strip()
        if not re.match(r"^[EW]_\w+$", name):
            continue
        names[code] = name
        code += 1
    return names


def messages(text, array_name, start_code):
    """Map code -> message for a const char *array[] = { ... }; table."""
    i = text.index(array_name)
    i = text.index("{", i)
    j = text.index("};", i)
    body = text[i + 1 : j]
    # One pass: string literals, line comments (ignored, they may contain
    # quotes or commas, as in URLs), and the commas that separate entries.
    tokens = re.findall(r'"((?:[^"\\]|\\.)*)"|(//[^\n]*)|(,)', body)
    result = {}
    current = []
    code = start_code
    for literal, comment, comma in tokens:
        if comment:
            continue
        if comma:
            result[code] = "".join(current)
            current = []
            code += 1
        else:
            current.append(literal)
    if current:
        result[code] = "".join(current)
    return result


def tidy(msg):
    msg = msg.replace("\\n", " ").replace('\\"', '"')
    msg = re.sub(r"`%(\d+\$)?s'", "`X`", msg)            # `%s' and the positional `%1$s'
    msg = re.sub(r"%(\d+\$)?[-0-9.]*[sdif]", "X", msg)
    return re.sub(r"\s+", " ", msg).strip()


def main():
    hh = (ROOT / "logger.hh").read_text(encoding="utf-8", errors="replace")
    cc = (ROOT / "logger.cc").read_text(encoding="utf-8", errors="replace")
    errors = messages(cc, "error_messages[]", 10000)
    warnings = messages(cc, "warning_messages[]", 20000)
    enames = enum_names(hh, "E_ERROR", 10000)
    wnames = enum_names(hh, "W_WARNING", 20000)

    lines = [
        "# lslint error and warning codes",
        "",
        "Generated by `gen_error_codes.py` from `logger.hh` and `logger.cc`. Codes",
        "are shown with `-#`. `X` stands for a value filled in at runtime (a name, a",
        "type, a position). Errors (1xxxx) mean the script will not compile in",
        "Second Life. Warnings (2xxxx) compile but very likely do not do what the",
        "author meant.",
        "",
        "## Errors",
        "",
        "| Code | Name | Message |",
        "| --- | --- | --- |",
    ]
    for code in sorted(errors):
        name = enames.get(code, "")
        if code == 10000 or "removed" in name:
            continue
        lines.append("| E%d | `%s` | %s |" % (code, name, tidy(errors[code])))
    lines += ["", "## Warnings", "", "| Code | Name | Message |", "| --- | --- | --- |"]
    for code in sorted(warnings):
        name = wnames.get(code, "")
        if code == 20000 or "removed" in name:
            continue
        lines.append("| E%d | `%s` | %s |" % (code, name, tidy(warnings[code])))
    lines.append("")
    OUT.parent.mkdir(exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as handle:   # Path.write_text has no newline= before Python 3.10
        handle.write("\n".join(lines))
    print("wrote %s (%d errors, %d warnings)" % (OUT.relative_to(ROOT), len(errors) - 1, len(warnings) - 1))
    return 0


if __name__ == "__main__":
    sys.exit(main())
